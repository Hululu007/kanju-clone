import { chromium } from 'file:///C:/Users/kenzh/AppData/Roaming/npm/node_modules/rea-agents/node_modules/playwright-core/index.mjs'
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--mute-audio','--no-first-run'] })
const ctx = await b.newContext({ viewport: { width: 1400, height: 900 }, locale: 'zh-CN' })
const p = await ctx.newPage()
await p.goto('https://kanju17.com/', { waitUntil: 'domcontentloaded', timeout: 60000 })
await p.waitForTimeout(15000)
await p.getByLabel('影视搜索输入').fill('嫁金钗')
await p.keyboard.press('Enter')
await p.waitForTimeout(8000)
const vids = await p.evaluate(() => [...document.querySelectorAll('video')].map(v => ({w:v.videoWidth,h:v.videoHeight,t:v.currentTime,d:v.duration,paused:v.paused,ready:v.readyState,src:(v.currentSrc||'').slice(0,80)})))
console.log('VIDEOS', JSON.stringify(vids))
const btns = await p.locator('button,[role=button]').evaluateAll(els => els.map(e => ({aria:e.getAttribute('aria-label'), txt:(e.innerText||'').trim().slice(0,24), title:e.getAttribute('title')})).filter(x=>x.txt||x.aria).slice(-40))
console.log('BTNS', JSON.stringify(btns, null, 0).slice(0,3000))
const txt = await p.locator('body').innerText()
console.log('TAILTEXT', txt.slice(-1500).replace(/\n+/g,' | '))
await p.screenshot({ path: 'outputs/acceptance-100/raw/origin-player.png' })
await b.close()
